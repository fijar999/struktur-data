# berbagai jenis tuple
my_tuple = ()
print(my_tuple)

# tuple berisi integer
my_tuple = (1, 2, 3)
print(my_tuple)

# tuple dengan campuran tipe data
my_tuple = (1, "Hello", 3.4)
print(my_tuple)

# tuple bersarang
my_tuple = ("python", [8, 4, 6], (1, 2, 3))
print(my_tuple)


var1 = ("Hello")    # string
var2 = ("Hello",)   # tuple

print(type(var1))
print(type(var2))

# tanda kurung tidak wajib, koma yang membentuk tuple satu elemen
var3 = "hello",
print(type(var3))